local stopCodons = { UAA = true, UAG = true, UGA = true }

local function findStop(rna, start)
    for i = start + 3, #rna - 2, 3 do
        if stopCodons[rna:sub(i, i + 2)] then return i end
    end
end

local function findSequences(rna)
    local sequences = {}
    local start = rna:find("AUG")
    while start do
        local stop = findStop(rna, start)
        if stop then
            table.insert(sequences, { first = start, last = stop + 2, text = rna:sub(start, stop + 2) })
        end
        start = rna:find("AUG", start + 1)
    end
    return sequences
end

local function contains(outer, inner)
    return outer ~= inner and outer.first <= inner.first and inner.last <= outer.last
end

local rna = S:upper():gsub("%s", ""):gsub("T", "U")
local sequences = findSequences(rna)

local best
for _, outer in ipairs(sequences) do
    outer.count = 0
    for _, inner in ipairs(sequences) do
        if contains(outer, inner) then outer.count = outer.count + 1 end
    end
    print(string.format("%4d - %4d contains %2d sequences", outer.first, outer.last, outer.count))
    if not best or outer.count > best.count then best = outer end
end

print()
print(string.format("Most subsequences: %d - %d with %d", best.first, best.last, best.count))
print(best.text)
