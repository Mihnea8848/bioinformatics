local stopCodons = { UAA = true, UAG = true, UGA = true }

local function findStop(rna, start)
    for i = start + 3, #rna - 2, 3 do
        if stopCodons[rna:sub(i, i + 2)] then return i end
    end
end

local rna = S:upper():gsub("%s", ""):gsub("T", "U")
local starts, withStop = 0, 0

local start = rna:find("AUG")
while start do
    starts = starts + 1
    local stop = findStop(rna, start)
    if stop then
        withStop = withStop + 1
        print(string.format("AUG at %4d -> %s at %4d (%d codons)", start, rna:sub(stop, stop + 2), stop, (stop - start) / 3))
    else
        print(string.format("AUG at %4d -> no stop codon", start))
    end
    start = rna:find("AUG", start + 1)
end

print()
print("Sequence length:        " .. #rna)
print("Possible start codons:  " .. starts)
print("Followed by a stop:     " .. withStop)
print("Without a stop:         " .. starts - withStop)
